def list_presets() -> list:
    """给前端用的预设清单。"""
    return [{"name": k, "label": v["label"], "desc": v["desc"]}
            for k, v in PRESETS.items()]


def get_overlay(name: str):
    """返回某预设的覆盖层（深拷贝）；default 返回 None。未知名字抛 KeyError。"""
    if name not in PRESETS:
        raise KeyError(name)
    ov = PRESETS[name]["overlay"]
    return deepcopy(ov) if ov is not None else None
