# 版本预设（ldcs/presets.py）
# ---------------------------------------------------------------------------
def get_preset_name() -> str:
    """当前生效的版本预设名。"""
    return str(get_config().get("preset") or "default")


def apply_preset(name: str) -> dict:
    """切换到某个版本预设，返回切换后生效的 config。

    - default    ：删除用户配置文件，回到 DEFAULT_CONFIG（原始行为）。
    - agent_spec ：「话务员规范版」覆盖层 deep-merge 到 DEFAULT_CONFIG。

    版本只换话术 / 提示词，**不动画布拓扑** —— 会保留用户当前的 flow。
    """
    from .presets import get_overlay
    overlay = get_overlay(name)  # 未知名字抛 KeyError
    if overlay is None:
        return reset_config()
    cur = get_config()
    merged = _deep_merge(deepcopy(DEFAULT_CONFIG), overlay)
    if cur.get("flow"):
        merged["flow"] = deepcopy(cur["flow"])
    return save_config(merged)


def _invalidate_cache():
    global _cached_config, _cached_mtime
    _cached_config = None
    _cached_mtime = 0.0
