# 运行时存储
# ---------------------------------------------------------------------------
CONFIG_DIR = Path(__file__).resolve().parent.parent / "config"
CONFIG_PATH = CONFIG_DIR / "workflow.json"

_cached_config: dict | None = None
_cached_mtime: float = 0.0


def _deep_merge(base: dict, overlay: dict) -> dict:
    """深合并：overlay 中的 key 覆盖 base；值是 dict 则递归。"""
    out = dict(base)
    for k, v in (overlay or {}).items():
        if k in out and isinstance(out[k], dict) and isinstance(v, dict):
            out[k] = _deep_merge(out[k], v)
        else:
            out[k] = v
    return out


def get_config() -> dict:
    """读当前配置（每请求检查文件 mtime，变化时自动重读）。"""
    global _cached_config, _cached_mtime
    mtime = CONFIG_PATH.stat().st_mtime if CONFIG_PATH.exists() else 0.0
    if _cached_config is None or mtime != _cached_mtime:
        user_cfg: dict = {}
        if CONFIG_PATH.exists():
            try:
                user_cfg = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
            except Exception:
                user_cfg = {}
        _cached_config = _deep_merge(DEFAULT_CONFIG, user_cfg)
        _cached_mtime = mtime
    return _cached_config


def save_config(new_cfg: dict) -> dict:
    """保存配置到 workflow.json。返回最终生效的 config。"""
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    CONFIG_PATH.write_text(
        json.dumps(new_cfg, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    _invalidate_cache()
    return get_config()


def reset_config() -> dict:
    """删除用户配置文件，恢复到 DEFAULT_CONFIG。"""
    if CONFIG_PATH.exists():
        CONFIG_PATH.unlink()
    _invalidate_cache()
    return get_config()


